#pragma once
#include <Arduino.h>

// =========================================================
// 麦克纳姆轮运动学控制库
//
// 使用前先调用 mecanumInit() 传入底盘几何参数：
//   axle_width_m    : 左右轮中心距，单位 m
//   axle_length_m   : 前后轮中心距，单位 m
//   wheel_diameter_m: 轮子直径，单位 m
//
// 通道映射 (以小车正前方为前):
//   FL (左前): Motor1 / 通道0
//   BL (左后): Motor2 / 通道1
//   BR (右后): Motor3 / 通道2
//   FR (右前): Motor4 / 通道3
//
// 速度方向约定:
//   Vx > 0  → 前进      Vx < 0  → 后退
//   Vy > 0  → 向右平移  Vy < 0  → 向左平移
//   Wz > 0  → 逆时针/左转  Wz < 0  → 顺时针/右转
//
// 平移速度约定:
//   vx 和 vy 共同决定平移方向角。
//   平移速度标量不取 sqrt(vx^2 + vy^2)，而取 max(|vx|, |vy|)。
//   也就是说，斜向移动时速度保持为两轴中较大的那个，不会因为矢量和额外增大。
//
// 线速度逆运动学方程:
//   v_FL = +Vx + Vy - (L+W)/2 * Wz
//   v_BL = +Vx - Vy - (L+W)/2 * Wz
//   v_BR = +Vx + Vy + (L+W)/2 * Wz
//   v_FR = +Vx - Vy + (L+W)/2 * Wz
//
// 其中 Vx、Vy 单位为 m/s，Wz 单位为 rad/s。
// 线速度再通过轮子周长换算为目标 RPM 后发送到底层控制板。
// =========================================================

// ---------------------------------------------------------
// mecanumInit — 初始化底盘几何参数
// ---------------------------------------------------------
void mecanumInit(float axle_width_m, float axle_length_m, float wheel_diameter_m);

// ---------------------------------------------------------
// mecanumSetVelocity — 连续速度控制（纯速度环，不设距离限制）
//
// vx    : 前后速度，单位 m/s（正=前进，负=后退）
// vy    : 左右速度，单位 m/s（正=向右平移，负=向左平移）
// wz    : 自转速度，单位 rad/s（正=逆时针/左转，负=顺时针/右转）
// ---------------------------------------------------------
void mecanumSetVelocity(float vx, float vy, float wz);

// ---------------------------------------------------------
// mecanumMoveDistance — 按距离控制运动（四路同步）
//
// vx, vy, wz  : 底盘速度，单位分别为 m/s、m/s、rad/s
// dist_m      : 运动距离，单位 m；<=0 时退化为纯速度环
//
// 注意：底层同步运动接口的距离参数是公共标量，方向由各轮 RPM 符号决定，
// 因此这里的 dist_m 应传入正值大小。
// ---------------------------------------------------------
bool mecanumMoveDistance(float vx, float vy, float wz, float dist_m);

// ---------------------------------------------------------
// mecanumRotateAngle — 原地按角度旋转（四路同步距离控制）
//
// wz        : 自转角速度，单位 rad/s（正=逆时针/左转，负=顺时针/右转）
// angle_rad : 旋转角度，单位 rad；只取绝对值，不参与方向判断
//
// 方向只由 wz 的正负号决定，和 mecanumSetVelocity() 的 wz 方向一致。
// 底层同步运动距离按轮缘弧长换算，并应用实车旋转距离补偿。
// wz=0 或 angle_rad=0 时直接清零速度目标。
// ---------------------------------------------------------
bool mecanumRotateAngle(float wz, float angle_rad);

// ---------------------------------------------------------
// mecanumStop — 停止所有电机
//
// brake : true  = 主动刹车后清零目标速度
//         false = 直接将目标速度清零（滑行停止）
// ---------------------------------------------------------
void mecanumStop(bool brake = false);

// ---------------------------------------------------------
// mecanumWaitDone — 阻塞等待距离控制完成
//   轮询 REG_DIST_STATUS，全部完成时返回 true
//
// timeout_ms : 超时时间（毫秒），0 = 永久等待
// minimum_run_ms : 最短运行时间，避免命令刚下发时误判完成
// 返回 true = 正常完成；false = 超时
// ---------------------------------------------------------
bool mecanumWaitDone(uint32_t timeout_ms = 10000,
                     uint32_t minimum_run_ms = 500);
bool mecanumIsMotionDone();
